func TestACustomBasesVariantReplacementIsRefusedWhileAnotherRunIsAlive(t *testing.T) {
	t.Setenv(loop.StateEnv, t.TempDir())
	args, _ := fakeProfileInstall(t)
	home := os.Getenv("CAO_HOME_DIR")
	writeFile(t, filepath.Join(home, "agent-store/my-reviewer-high.md"), "original\n")
	run := statusFixture(t, filepath.Join(loop.StateDir(), "runs"), "other")
	child := statusChild(t)
	run.PID = child.Process.Pid
	var err error
	run.ProcessStart, err = processStart(run.PID)
	if err != nil {
		t.Fatal(err)
	}
	saveStatusFixture(t, filepath.Join(loop.StateDir(), "runs"), run.RunID, run)
	srv := permissionCAO(t, map[string]cao.ProfilePermissions{"my-reviewer": {PermissionMode: "default"}, "my-reviewer-high": {Description: "kapellmeister chair at high effort"}}, map[string]bool{"my-reviewer-high": true})
	p := loop.DefaultPolicy()
	err = ensureProfiles(context.Background(), cao.NewClient(srv.URL), &p, map[string][]loop.Chair{"plan": {{Provider: "claude_code", Profile: "my-reviewer"}}})
	if err == nil || !strings.Contains(err.Error(), "my-reviewer-high") || !strings.Contains(err.Error(), run.RunID) {
		t.Fatalf("error = %v", err)
	}
	if _, err := os.Stat(args); !os.IsNotExist(err) {
		t.Fatalf("installer called: %v", err)
	}
	data, _ := os.ReadFile(filepath.Join(home, "agent-store/my-reviewer-high.md"))
	if string(data) != "original\n" {
		t.Fatalf("original = %s", data)
	}
	if _, err := os.Stat(filepath.Join(loop.StateDir(), "profiles")); !os.IsNotExist(err) {
		t.Fatalf("variant written: %v", err)
	}
}

