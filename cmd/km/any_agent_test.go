func TestAUserNamedProfileGetsItsEffortVariantInstalledFromItsBase(t *testing.T) {
	t.Setenv(loop.StateEnv, t.TempDir())
	args, installed := fakeProfileInstall(t)
	srv := permissionCAO(t, map[string]cao.ProfilePermissions{"my-reviewer": {PermissionMode: "default", AllowedTools: []string{"Read"}}}, nil)
	p := loop.DefaultPolicy()
	steps := map[string][]loop.Chair{"plan": {{Provider: "claude_code", Profile: "my-reviewer"}}}
	if err := ensureProfiles(context.Background(), cao.NewClient(srv.URL), &p, steps); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(installed)
	if err != nil {
		t.Fatal(err)
	}
	for _, v := range p.EffortVariants(steps) {
		if !strings.Contains(string(data), "name: "+v.Name()+"\n") {
			t.Fatalf("missing %s: %s", v.Name(), data)
		}
	}
	if strings.Contains(string(data), "name: km-") || !strings.Contains(string(data), "permissionMode: default\nallowedTools: [\"Read\"]") {
		t.Fatalf("source = %s", data)
	}
	arguments, err := os.ReadFile(args)
	if err != nil || strings.Count(string(arguments), "--provider\nclaude_code\n") != len(p.EffortVariants(steps)) {
		t.Fatalf("installer arguments = %s, %v", arguments, err)
	}

}

