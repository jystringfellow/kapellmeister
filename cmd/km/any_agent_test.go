const customAgentConfig = `[agents]
available = ["mine"]
[agents.define]
mine = "claude_code:my-reviewer"
`

func TestAUserDefinedAgentIsSeatedAtATieredChairWithoutAnyKmProfile(t *testing.T) {
	t.Setenv(loop.HomeEnv, t.TempDir())
	t.Setenv(loop.StateEnv, t.TempDir())
	_, installed := fakeProfileInstall(t)
	writeFile(t, loop.UserConfigPath(loop.Home()), customAgentConfig)
	base := permissionCAO(t, map[string]cao.ProfilePermissions{"my-reviewer": {PermissionMode: "default", AllowedTools: []string{"Read"}}}, nil)
	var mu sync.Mutex
	var launches []string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		mu.Lock()
		if (strings.HasPrefix(strings.TrimPrefix(r.URL.Path, "/agents/profiles/"), "km-") && !strings.HasPrefix(strings.TrimPrefix(r.URL.Path, "/agents/profiles/"), "km-probe-")) || strings.HasPrefix(r.URL.Query().Get("agent_profile"), "km-") {
			t.Errorf("km profile requested: %s", r.URL)
		}
		if r.Method == "POST" && (r.URL.Path == "/sessions" || strings.HasSuffix(r.URL.Path, "/terminals")) {
			launches = append(launches, r.URL.Query().Get("agent_profile"))
		}
		mu.Unlock()
		base.Config.Handler.ServeHTTP(w, r)
	}))
	defer srv.Close()
	s, err := loop.LoadSettings(loop.Home(), "")
	if err != nil {
		t.Fatal(err)
	}
	wt := t.TempDir()
	s, chairs, members, err := lineUp(s, wt, "", nil)
	if err != nil {
		t.Fatal(err)
	}
	client := cao.NewClient(srv.URL)
	if err := ensureProfiles(context.Background(), client, &s.Policy, stepChairs(chairs)); err != nil {
		t.Fatal(err)
	}
	sizeMembers(s.Policy, members)
	report, err := (ensemble.Audition{Client: client, Ensemble: "custom", Worktree: wt, Members: members, Timeout: time.Minute, KM: "km"}).Run(context.Background())
	if err != nil || !report.OK {
		t.Fatalf("report = %+v, %v", report, err)
	}
	if len(launches) != len(loop.ChairRoles) {
		t.Fatalf("launches = %v", launches)
	}
	for _, profile := range launches {
		if !strings.HasPrefix(profile, "my-reviewer-") {
			t.Fatalf("launch = %s", profile)
		}
	}
	data, err := os.ReadFile(installed)
	if err != nil || strings.Contains(string(data), "km-") || !strings.Contains(string(data), "name: my-reviewer-high") {
		t.Fatalf("installed = %s, %v", data, err)
	}
}

